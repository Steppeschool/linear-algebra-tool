#!/usr/bin/env python3
"""Make assets/embed.css: lesson.css with every rule scoped under .la-embed,
so the lessons can be pasted into a Kajabi lesson without restyling Kajabi's own page."""
import pathlib, re

ROOT = pathlib.Path(__file__).parent
SCOPE = ".la-embed"


def scope_selector(sel):
    sel = sel.strip()
    if not sel:
        return sel
    # page-level selectors become the wrapper itself
    sel = re.sub(r'^:root\[data-theme="?(\w+)"?\]', SCOPE + r'[data-theme="\1"]', sel)
    sel = re.sub(r'^:root:not\(\[data-theme="?(\w+)"?\]\)', SCOPE + r':not([data-theme="\1"])', sel)
    if sel in (":root", "html", "body", "html,body"):
        return SCOPE
    sel = re.sub(r'^(html|body)\b', SCOPE, sel)
    if sel.startswith(SCOPE):
        return sel
    if sel == "*":
        return f"{SCOPE}, {SCOPE} *"
    return f"{SCOPE} {sel}"


def scope_block(css):
    out, i = [], 0
    while i < len(css):
        j = css.find("{", i)
        if j < 0:
            out.append(css[i:]); break
        head = css[i:j].strip()
        # find matching brace
        depth, k = 1, j + 1
        while depth and k < len(css):
            depth += {"{": 1, "}": -1}.get(css[k], 0); k += 1
        body = css[j + 1:k - 1]
        if head.startswith("@media") or head.startswith("@supports"):
            out.append(f"{head}{{{scope_block(body)}}}")
        elif head.startswith("@"):
            out.append(f"{head}{{{body}}}")
        else:
            head = re.sub(r"/\*.*?\*/", "", head, flags=re.S).strip()
            sels = ", ".join(scope_selector(s) for s in head.split(","))
            out.append(f"{sels}{{{body}}}")
        i = k
    return "\n".join(out)


css = (ROOT / "assets" / "lesson.css").read_text(encoding="utf-8")
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
scoped = scope_block(css)
# Kajabi pages are light, so the embed stays light: drop the dark-theme overrides
scoped = re.sub(r'@media \(prefers-color-scheme: dark\)\{.*?\}\}', '', scoped, flags=re.S)
scoped = re.sub(r'\.la-embed\[data-theme="dark"\]\{.*?\}', '', scoped, flags=re.S)
# Respond to the width of the lesson column, not the browser window: Kajabi's column is narrow.
container = []
for m in re.finditer(r'@media \((max-width:\d+px)\)\{', scoped):
    depth, k = 1, m.end()
    while depth and k < len(scoped):
        depth += {"{": 1, "}": -1}.get(scoped[k], 0); k += 1
    container.append(f"@container la ({m.group(1)}){{{scoped[m.end():k - 1]}}}")
scoped += "\n" + "\n".join(container)
# Kajabi's theme styles plain tags (li, p, h1...). Reset them inside the lesson so its layout matches the site.
scoped += """
.la-embed{container-type:inline-size;container-name:la}
.la-embed p,.la-embed ul,.la-embed ol,.la-embed li,.la-embed h1,.la-embed h2,.la-embed h3,.la-embed figure,.la-embed pre,.la-embed details,.la-embed summary,.la-embed section{line-height:inherit;letter-spacing:normal;text-transform:none;color:inherit}
.la-embed li{margin:0;padding:0}
.la-embed .ideas{gap:6px}
.la-embed .prose ul{margin:0 0 12px}
.la-embed .prose li{margin-bottom:6px}
.la-embed p{margin:0 0 12px}
.la-embed h1,.la-embed h2,.la-embed h3{text-transform:none}
.la-embed .kicker,.la-embed .ideas-h,.la-embed .prose h3,.la-embed .example h3,.la-embed .sl-h,.la-embed .outhead{text-transform:uppercase}
.la-embed button,.la-embed input,.la-embed textarea{font:inherit;letter-spacing:normal;text-transform:none;box-shadow:none}
.la-embed .code textarea{font-family:var(--f-mono)}
"""
# the wrapper needs its own background and text colour, since Kajabi's body does not have ours
scoped += f"\n{SCOPE}{{background:var(--paper);color:var(--ink);font-family:var(--f-body);font-size:16px;line-height:1.65;padding:16px;border-radius:16px}}\n"
(ROOT / "assets" / "embed.css").write_text("/* generated by tools_embed.py from lesson.css: do not edit by hand */\n" + scoped, encoding="utf-8")
print("embed.css", len(scoped), "bytes")
